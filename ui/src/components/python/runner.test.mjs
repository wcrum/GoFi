import { test } from 'node:test'
import assert from 'node:assert/strict'
import { buildLogItems, filterLogItems, formatDuration, isRuntimeLine } from './log-model.ts'
import { managedView, parseManagedSource, stageEntryLines, viewLine } from './managed-source.ts'
import { workerState } from './worker-state.ts'

const sys = (line, extra = {}) => ({ stream: 'system', line, invocationId: '', function: '', ...extra })

test('lifecycle rows, hidden runtime boilerplate, and grouped runs', () => {
  const entries = [
    sys('worker starting'),
    sys('worker ready: listener telemetry, parser telemetry, transformer enrich'),
    sys('Started server process [7]'),
    sys('Waiting for application startup.'),
    sys('Application startup complete.'),
    sys('Uvicorn running on http://0.0.0.0:8080 (Press CTRL+C to quit)'),
    { stream: 'system', line: 'invocation started: transformer enrich', invocationId: 'run1', function: 'enrich', kind: 'transformer', time: '2026-10-16T10:00:00Z' },
    { stream: 'stdout', line: 'hello', invocationId: 'run1', function: 'enrich', kind: 'transformer' },
    { stream: 'stderr', line: 'careful', invocationId: 'run1', function: 'enrich', kind: 'transformer' },
    { stream: 'system', line: 'invocation finished in 1534 us', invocationId: 'run1', function: 'enrich', kind: 'transformer' },
    { stream: 'system', line: 'invocation started: parser telemetry', invocationId: 'run2', function: 'telemetry', kind: 'parser' },
    { stream: 'system', line: 'invocation failed after 900 us at line 7: KeyError: \'x\'', invocationId: 'run2', function: 'telemetry', kind: 'parser', level: 'error' },
    sys('worker stopped; reattaching when it is running again'),
  ]
  const hidden = buildLogItems(entries, false)
  assert.deepEqual(hidden.map(item => item.type), ['lifecycle', 'lifecycle', 'run', 'run', 'lifecycle'])
  assert.equal(hidden[0].tone, 'starting')
  assert.deepEqual(hidden[1].functions, ['listener telemetry', 'parser telemetry', 'transformer enrich'])
  assert.equal(hidden[4].tone, 'stopped')
  const [ok, failed] = [hidden[2], hidden[3]]
  assert.equal(ok.outcome, 'ok'); assert.equal(ok.durationUs, 1534); assert.equal(ok.function, 'enrich')
  assert.deepEqual(ok.lines.map(line => [line.text, line.severity]), [['hello', 'output'], ['careful', 'stderr']])
  assert.equal(failed.outcome, 'error'); assert.equal(failed.errorLine, 7); assert.equal(failed.error, "KeyError: 'x'")
  assert.equal(buildLogItems(entries, true).filter(item => item.type === 'runtime').length, 4)
  assert.ok(isRuntimeLine(sys('Uvicorn running on http://0.0.0.0:8080')))
  assert.ok(!isRuntimeLine({ ...sys('Uvicorn running on x'), invocationId: 'r' }))
  assert.deepEqual(filterLogItems(hidden, '', 'run2').map(item => item.id), ['run2'])
  assert.deepEqual(filterLogItems(hidden, 'careful').map(item => item.type), ['run'])
  assert.equal(formatDuration(1534), '1.5 ms'); assert.equal(formatDuration(350), '350 µs'); assert.equal(formatDuration(2_410_000), '2.41 s')
})

test('a run still in progress stays running; drops are distinguished', () => {
  const items = buildLogItems([
    { stream: 'stdout', line: 'working', invocationId: 'a', function: 'f', kind: 'transformer' },
    { stream: 'system', line: 'invocation started: transformer g', invocationId: 'b', function: 'g', kind: 'transformer' },
    { stream: 'system', line: 'invocation finished in 10 us (dropped)', invocationId: 'b', function: 'g', kind: 'transformer' },
  ], false)
  assert.equal(items[0].outcome, 'running')
  assert.equal(items[1].outcome, 'dropped')
})

test('managed library source renders as readable stage code', () => {
  const generated = '# Generated by GoFi from listener "c2-inline" inline stages. Do not edit.\nimport gofi as _gofi\n' +
    '_gofi._inline("inl", "def transform(fields, meta):\\n    total = 0\\n    print(\\"inline c2\\", total)\\n    return fields\\n")\n' +
    '_gofi._inline("two", "import math\\n\\ndef transform(fields):\\n    return fields\\n")\n'
  const stages = parseManagedSource(generated)
  assert.deepEqual(stages.map(stage => stage.id), ['inl', 'two'])
  assert.equal(stages[0].source.split('\n')[2], '    print("inline c2", total)')
  const view = managedView('c2-inline', stages)
  const lines = view.text.split('\n')
  assert.ok(!view.text.includes('_gofi._inline'))
  assert.equal(lines[view.offsets.inl - 1], 'def transform(fields, meta):')
  assert.equal(lines[view.offsets.two - 1], 'import math')
  assert.equal(lines[viewLine(view, 'two', 3) - 1], 'def transform(fields):')
  assert.equal(stageEntryLines(view).two, view.offsets.two + 2)
  assert.equal(viewLine(view, 'missing', 4), 4)
  assert.equal(parseManagedSource('import gofi\n@gofi.parser("x")\ndef x(data): return data\n'), null)
})

test('worker state reads Starting after Ready as a restart', () => {
  assert.equal(workerState({ phase: 'Starting' }).text, 'Starting worker…')
  assert.equal(workerState({ phase: 'Starting' }, 'Ready').text, 'Restarting worker…')
  assert.equal(workerState({ phase: 'Ready' }).tone, 'success')
  const failed = workerState({ phase: 'Failed', error: 'boom' })
  assert.equal(failed.tone, 'error'); assert.equal(failed.tooltip, 'boom')
  assert.equal(workerState(undefined).text, 'Stopped')
})

test('worker startup rows read in order and stop spinning once ready', () => {
  const t = '2026-10-17T19:14:33.142Z'
  const entries = [
    { time: '2026-10-17T19:14:33.136Z', stream: 'system', line: 'worker starting', level: 'info' },
    { time: t, stream: 'system', line: 'worker ready: decoder strip_dev', level: 'info' },
    { time: t, stream: 'system', line: 'Started server process [7]', level: 'info' },
    { time: t, stream: 'system', line: 'Application startup complete.', level: 'info' },
  ]
  const items = buildLogItems(entries, true)
  const kinds = items.map(i => i.type === 'lifecycle' ? `${i.tone}${i.settled ? '(settled)' : ''}` : i.type)
  assert.equal(kinds[0], 'starting(settled)')
  assert.equal(kinds[kinds.length - 1], 'ready')
  assert.ok(!kinds.slice(1, -1).includes('ready'))
})
