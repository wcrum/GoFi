package sandbox

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"

	"github.com/wcrum/gofi/spec"
)

// InlineFilename is the traceback filename of an inline stage; worker error
// locations are reported relative to the snippet the user wrote.
func InlineFilename(function string) string { return "<gofi-inline:" + function + ">" }

func pyString(value string) string {
	var buffer bytes.Buffer
	encoder := json.NewEncoder(&buffer)
	encoder.SetEscapeHTML(false)
	_ = encoder.Encode(value) // JSON string literals are valid Python literals.
	return strings.TrimSpace(buffer.String())
}

// WrapInline registers one inline snippet as transformer `function` through
// the SDK's gofi._inline: each snippet executes in its own namespace, so
// names never collide across stages, and keeps its own line numbers (under
// InlineFilename) for diagnostics, entry lines, and line traces.
func WrapInline(function, source string) string {
	return fmt.Sprintf("_gofi._inline(%s, %s)\n", pyString(function), pyString(source))
}

// InlineLibrary builds the managed library for a listener's inline stages,
// or reports false when the listener has none.
func InlineLibrary(def spec.FlowDefinition) (Definition, bool) {
	stages := def.InlineStages()
	if len(stages) == 0 {
		return Definition{}, false
	}
	var source strings.Builder
	source.WriteString("# Generated by GoFi from listener " + pyString(def.Name) + " inline stages. Do not edit.\nimport gofi as _gofi\n")
	for _, stage := range stages {
		source.WriteString(WrapInline(stage.ID, stage.Python.InlineSource))
	}
	return Definition{Name: spec.ManagedLibraryName(def.Name), SourceCode: source.String(), ManagedBy: spec.ManagedBy(def.Name)}, true
}

// InlineBinding returns a ready managed worker already running exactly this
// snippet as `function`, so simulations of saved inline stages avoid
// starting a scratch worker.
func (s *Supervisor) InlineBinding(function, source string) (Binding, bool) {
	wrapped := WrapInline(function, source)
	s.mu.RLock()
	defer s.mu.RUnlock()
	for name, d := range s.defs {
		if !d.Managed() || !strings.Contains(d.SourceCode, wrapped) || s.statuses[name].Phase != "Ready" {
			continue
		}
		if binding, ok := s.bindings[name]; ok {
			return binding, true
		}
	}
	return Binding{}, false
}
