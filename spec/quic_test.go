// testCertPEM is a minimal self-signed certificate for PEM-shape checks.
func testCertPEM(t *testing.T) string {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	tmpl := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "test"}, NotBefore: time.Now().Add(-time.Minute), NotAfter: time.Now().Add(time.Hour), IsCA: true, BasicConstraintsValid: true}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	return string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}))
}

// A valid certificate and key pair is generated by the quictls package;
// spec tests use the built-in structure checks with syntactically invalid
// PEM and the cross-field rules instead.
func TestListenSourceQUICValidation(t *testing.T) {
	cases := []struct {
		name string
		src  ListenSource
		want string // substring of the error; "" means valid
	}{
		{"tcp default", ListenSource{Port: 1}, ""},
		{"quic with port", ListenSource{Network: "quic", Port: 4433}, ""},
		{"quic needs port", ListenSource{Network: "quic"}, "port is required for network quic"},
		{"unknown network", ListenSource{Network: "sctp", Port: 1}, "tcp, udp, or quic"},
		{"tls on tcp", ListenSource{Network: "tcp", Port: 1, TLS: &TLSConfig{}}, "tls requires network quic"},
		{"cert without key", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{Cert: "x"}}, "cert and key must be set together"},
		{"key without cert", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{Key: "x"}}, "cert and key must be set together"},
		{"bad key pair", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{Cert: "x", Key: "y"}}, "matching PEM"},
		{"bad ca", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{CA: "not pem"}}, "ca must be a PEM"},
		{"skip verify on source", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{InsecureSkipVerify: true}}, "insecureSkipVerify applies to QUIC sinks"},
		{"server name on source", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{ServerName: "x"}}, "serverName applies to QUIC sinks"},
		{"require client cert without ca", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{RequireClientCert: true}}, "requireClientCert requires ca"},
		{"bad alpn", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{ALPN: []string{"a b"}}}, "alpn entries"},
		{"custom alpn", ListenSource{Network: "quic", Port: 1, TLS: &TLSConfig{ALPN: []string{"custom/2"}}}, ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := tc.src.Validate()
			if tc.want == "" {
				if err != nil {
					t.Fatalf("unexpected error: %v", err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("error = %v, want %q", err, tc.want)
			}
		})
	}
}

func TestTLSConfigClientValidation(t *testing.T) {
	if err := (*TLSConfig)(nil).Validate("sink tls", TLSClient); err != nil {
		t.Fatalf("nil config: %v", err)
	}
	if err := (&TLSConfig{RequireClientCert: true}).Validate("sink tls", TLSClient); err == nil || !strings.Contains(err.Error(), "listen sources only") {
		t.Fatalf("requireClientCert on a client: %v", err)
	}
	ca := testCertPEM(t)
	if err := (&TLSConfig{InsecureSkipVerify: true, CA: ca}).Validate("sink tls", TLSClient); err == nil || !strings.Contains(err.Error(), "not both") {
		t.Fatalf("ca with insecureSkipVerify: %v", err)
	}
	if err := (&TLSConfig{CA: ca}).Validate("sink tls", TLSClient); err != nil {
		t.Fatalf("valid ca: %v", err)
	}
	if err := (&TLSConfig{CA: ca, RequireClientCert: true}).Validate("source.listen.tls", TLSServer); err != nil {
		t.Fatalf("valid source ca: %v", err)
	}
	if err := (&TLSConfig{ServerName: "bad host"}).Validate("sink tls", TLSClient); err == nil {
		t.Fatal("server name with whitespace accepted")
	}
	if err := (&TLSConfig{InsecureSkipVerify: true, ServerName: "dest"}).Validate("sink tls", TLSClient); err != nil {
		t.Fatalf("plain client config: %v", err)
	}
}

func TestTLSConfigDefaults(t *testing.T) {
	var cfg *TLSConfig
	if got := cfg.ALPNProtocols(); len(got) != 1 || got[0] != DefaultQUICALPN {
		t.Fatalf("nil ALPN = %v", got)
	}
	if got := (&TLSConfig{ALPN: []string{"x", "y"}}).ALPNProtocols(); len(got) != 2 || got[0] != "x" {
		t.Fatalf("custom ALPN = %v", got)
	}
	if cfg.HasKeyPair() || (&TLSConfig{Cert: "c"}).HasKeyPair() {
		t.Fatal("HasKeyPair without both parts")
	}
	for network, protocol := range map[string]string{"": "tcp", "tcp": "tcp", "udp": "udp", "quic": "udp"} {
		if got := (ListenSource{Network: network}).Protocol(); got != protocol {
			t.Errorf("Protocol(%q) = %q, want %q", network, got, protocol)
		}
	}
	if (ListenSource{}).NetworkOrDefault() != "tcp" || (ListenSource{Network: "quic"}).NetworkOrDefault() != "quic" {
		t.Fatal("NetworkOrDefault")
	}
}

func TestFlowSourceAcceptsQUICListenJSON(t *testing.T) {
	var src FlowSource
	data := `{"listen":{"network":"quic","port":4433,"tls":{"ca":"-----BEGIN CERTIFICATE-----\nAA==\n-----END CERTIFICATE-----\n","requireClientCert":true,"alpn":["gofi/1"]}}}`
	if err := src.UnmarshalJSON([]byte(data)); err != nil {
		t.Fatalf("unmarshal: %v", err)
	}
	if src.Listen == nil || src.Listen.TLS == nil || !src.Listen.TLS.RequireClientCert || src.Listen.Network != NetworkQUIC {
		t.Fatalf("decoded %+v", src.Listen)
	}
}
